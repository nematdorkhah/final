-- 1) آیا توابع لازم نصب شده‌اند؟ (هر سطری که installed = false باشد، فایل migration مربوطش اجرا نشده)
SELECT f.name,
       EXISTS (SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
               WHERE n.nspname = 'public' AND p.proname = f.name) AS installed
FROM (VALUES
  ('student_poll_fingerprint'), ('teacher_poll_fingerprint'),
  ('student_list_published_quizzes'), ('teacher_list_quizzes'), ('teacher_upsert_quiz'),
  ('student_list_my_quiz_submissions'), ('student_upsert_quiz_submission'),
  ('teacher_list_quiz_submissions'), ('teacher_upsert_quiz_submission'),
  ('student_get_exam_review'),
  ('student_upsert_tizhooshan'), ('teacher_list_tizhooshan'),
  ('student_list_my_grades'), ('teacher_list_grades'),
  ('get_server_time'), ('student_log_exam_integrity'), ('teacher_list_exam_integrity')
) AS f(name)
ORDER BY installed, f.name;

